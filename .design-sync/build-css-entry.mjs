// Assemble the single cssEntry the converter appends into _ds_bundle.css.
// The converter's copyTokens() only reads from a node_modules package, and remote
// @import scraping is storybook-only — so for this repo the whole styles.css closure
// has to arrive through one file. Cascade order mirrors the real site:
// tokens (:root vars) → tailwind (base+utilities) → components.css (tc-* vocabulary).
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// ---------------------------------------------------------------------------
// Font Awesome.
//
// The site renders most icons through an SVG sprite (.tc-icon + <use href="/assets/
// icons/sprite.svg#fa-name">), but that href is site-absolute and cannot resolve inside
// a rendered design. Three components (.tc-trusty-line, .tc-lesson-trigger and the
// answer-card bullet) additionally set font-family:"Font Awesome 6 Free" with \fXXX
// content, which is plain tofu without the webfont.
//
// Shipping the real Font Awesome CSS + woff2 fixes both: the ::before glyphs render,
// and a design agent can write the ordinary <i class="fa-solid fa-check"> markup with
// no asset-path resolution involved. Same icon set the sprite was generated from.
// ---------------------------------------------------------------------------
const FA = 'node_modules/@fortawesome/fontawesome-free';
const FONTS_DIR = '.design-sync/fonts';
const faCss = readFileSync(join(FA, 'css/all.min.css'), 'utf8');

const faceBlocks = [...faCss.matchAll(/@font-face\{[^}]*\}/g)].map((m) => m[0]);
const faFaces = [];
const copied = new Set();

for (const block of faceBlocks) {
  const family = block.match(/font-family:\s*("[^"]+"|'[^']+'|[^;}]+)/)?.[1];
  const woff2 = block.match(/url\(\s*['"]?\.\.\/webfonts\/([^'")]+\.woff2)['"]?\s*\)/)?.[1];
  if (!family || !woff2) continue;

  if (!copied.has(woff2)) {
    copyFileSync(join(FA, 'webfonts', woff2), join(FONTS_DIR, woff2));
    copied.add(woff2);
  }
  const weight = block.match(/font-weight:\s*([^;}]+)/)?.[1]?.trim() ?? 'normal';
  const style = block.match(/font-style:\s*([^;}]+)/)?.[1]?.trim() ?? 'normal';
  // Rebuild the rule with the woff2 src only — the .ttf fallback would double the
  // uploaded font weight for no benefit in the design tool's chromium.
  faFaces.push(
    `@font-face{font-family:${family};font-style:${style};font-weight:${weight};` +
      `font-display:block;src:url(./${woff2}) format("woff2");}`,
  );
}

writeFileSync(
  join(FONTS_DIR, 'fontawesome.css'),
  `/* Font Awesome 6 Free @font-face rules, woff2 only — generated by build-css-entry.mjs */\n${faFaces.join('\n')}\n`,
);

// The icon classes (.fa-solid, .fa-check, …) belong in the stylesheet; the @font-face
// blocks are stripped because they ride in via cfg.extraFonts with corrected urls.
// A dead ../webfonts/ url left here would be dropped by the converter anyway, and a
// dropped face declared after the good one shadows it.
const faClasses = faceBlocks.reduce((css, b) => css.split(b).join(''), faCss);
if (/@font-face/.test(faClasses)) throw new Error('font-face blocks not fully stripped from FA css');


const tokens = readFileSync('site/assets/css/tokens.css', 'utf8');
const tailwind = readFileSync('.design-sync/css/tailwind.ds.css', 'utf8');

// Drop components.css's own @import of tokens.css — tokens are inlined above it here,
// and a nested relative @import would 404 from the bundle root.
const components = readFileSync('site/assets/css/components.css', 'utf8')
  .replace(/@import\s+url\(\s*["']\.\/tokens\.css["']\s*\)\s*;/g, '/* tokens.css inlined above by design-sync */');

if (/@import\s+url\(\s*["']\.\/tokens\.css/.test(components)) throw new Error('tokens @import not stripped');

const banner = `/* =========================================================================
 * TrustCore — design system stylesheet (generated for claude.ai/design)
 * Concatenated from the repo's own sources, in the site's cascade order:
 *   1. site/assets/css/tokens.css      — :root design tokens (--tc-*)
 *   2. .design-sync/css/tailwind.ds.css — Tailwind 3.4 w/ brand theme, broad safelist
 *   3. site/assets/css/components.css   — the tc-* component vocabulary
 *   4. Font Awesome 6 Free icon classes (webfonts ship via cfg.extraFonts)
 * Regenerate: node .design-sync/build-css-entry.mjs (see .design-sync/NOTES.md)
 * ========================================================================= */
`;

// The site ships progressive-enhancement JS (site/assets/js/components.js) that adds
// .is-revealed / .is-active at runtime. That script is deliberately NOT bundled here —
// it also fires analytics (dataLayer/gtag), which has no place in the design tool. But
// two rules below it start at opacity:0 and would render a design's content INVISIBLE
// with no JS to reveal it. This layer restores the resting (revealed) state, which is
// the correct static appearance for a design anyway.
const compat = `/* ---------- 4. design-tool compatibility ----------
 * Added by design-sync. The site's reveal/tab JS is not part of this bundle, so
 * elements it would un-hide are shown in their final state instead. */
[data-reveal] {
  opacity: 1;
  transform: none;
}
/* A theater stack with no .is-active panel yet: show the first one rather than all-blank. */
.tc-theater-stack:not(:has(> .tc-theater-panel.is-active)) > .tc-theater-panel:first-child {
  opacity: 1;
  visibility: visible;
  transform: none;
  pointer-events: auto;
}
`;

const out = [
  banner,
  '/* ---------- 1. tokens ---------- */',
  tokens,
  '/* ---------- 2. tailwind ---------- */',
  tailwind,
  '/* ---------- 3. components ---------- */',
  components,
  '/* ---------- 4. font awesome icon classes ---------- */',
  faClasses,
  compat,
].join('\n');

writeFileSync('.design-sync/css/trustcore-ds.css', out);
console.log(`wrote .design-sync/css/trustcore-ds.css (${(out.length / 1024).toFixed(0)} KB)`);
